def validar_idioma(codigo):
    """Valida y normaliza un código de idioma a uno de los soportados ('es', 'en', 'fr', 'pt')."""
    if not codigo:
        return IDIOMA_DEFAULT
    cod = str(codigo).strip().lower()[:2]
    return cod if cod in IDIOMAS_SOPORTADOS else IDIOMA_DEFAULT


def traducir(clave, idioma=IDIOMA_DEFAULT, default=None):
    """Traduce una clave semántica al idioma solicitado, con fallback a español."""
    lang = validar_idioma(idioma)
    catalogo = TRADUCCIONES.get(lang, TRADUCCIONES[IDIOMA_DEFAULT])
    if clave in catalogo:
        return catalogo[clave]
    if clave in TRADUCCIONES[IDIOMA_DEFAULT]:
        return TRADUCCIONES[IDIOMA_DEFAULT][clave]
    return default if default is not None else clave


def obtener_mapa_dom(idioma):
    """Retorna el diccionario de traducción de frases del DOM para el idioma activo."""
    lang = validar_idioma(idioma)
    return TRADUCCIONES_DOM.get(lang, {})
